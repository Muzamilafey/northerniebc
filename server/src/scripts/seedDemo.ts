/**
 * DEVELOPMENT/TEST ONLY. Creates a clearly-labelled synthetic election so the agent and
 * verification workflows can be exercised locally. Refuses to run in production, and every
 * record name starts with "DEMO" so it can never be mistaken for real data.
 */
import { env } from '../config/env.js';
import { connectMongo, disconnectMongo } from '../db/mongo.js';
import { AgentAssignment, Candidate, Constituency, County, DataSource, Election, PollingStation, User, Ward } from '../models/index.js';
import { hashPassword } from '../modules/auth/password.js';
import { seedReference } from './seedReference.js';

export async function seedDemo() {
  if (env.NODE_ENV === 'production') throw new Error('Refusing to seed demo data in production');
  await seedReference();
  const garissa = (await County.findOne({ code: '007' }))!;
  const src = await DataSource.findOneAndUpdate(
    { name: 'DEMO synthetic data — not a real source' },
    { $setOnInsert: { name: 'DEMO synthetic data — not a real source', kind: 'OTHER', verificationStatus: 'UNREVIEWED', notes: 'Generated by seedDemo for local testing' } },
    { upsert: true, new: true }
  );
  let election = await Election.findOne({ slug: 'demo-synthetic-election' });
  if (!election) {
    election = await Election.create({
      name: 'DEMO Synthetic Election (not real)',
      slug: 'demo-synthetic-election',
      type: 'BY_ELECTION',
      electionDate: new Date(),
      status: 'ACTIVE',
      countyIds: [garissa._id],
      publishProvisional: true,
      positions: [
        { position: 'GOVERNOR', enabled: true, requiredFields: ['validVotes', 'rejectedVotes'], rules: ['CANDIDATE_SUM_EQUALS_VALID', 'CAST_NOT_EXCEEDING_REGISTERED'], requireEvidence: false },
        { position: 'MCA', enabled: true, requiredFields: [], rules: ['CANDIDATE_SUM_EQUALS_VALID'], requireEvidence: false }
      ],
      sourceId: src!._id
    });
  }
  const cons = await Constituency.findOneAndUpdate({ electionId: election._id, code: 'DEMO-C1' }, { $setOnInsert: { electionId: election._id, countyId: garissa._id, code: 'DEMO-C1', name: 'DEMO Constituency One' } }, { upsert: true, new: true });
  const ward = await Ward.findOneAndUpdate({ electionId: election._id, code: 'DEMO-W1' }, { $setOnInsert: { electionId: election._id, countyId: garissa._id, constituencyId: cons!._id, code: 'DEMO-W1', name: 'DEMO Ward One' } }, { upsert: true, new: true });
  const stations = [];
  for (let i = 1; i <= 3; i++) {
    stations.push(
      await PollingStation.findOneAndUpdate(
        { electionId: election._id, code: `DEMO-PS${i}` },
        { $setOnInsert: { electionId: election._id, countyId: garissa._id, constituencyId: cons!._id, wardId: ward!._id, code: `DEMO-PS${i}`, name: `DEMO Polling Station ${i}`, registeredVoters: 700 } },
        { upsert: true, new: true }
      )
    );
  }
  for (const [i, name] of ['DEMO Candidate Alpha', 'DEMO Candidate Beta', 'DEMO Candidate Gamma'].entries()) {
    await Candidate.updateOne({ electionId: election._id, position: 'GOVERNOR', scopeRefId: garissa._id, fullName: name }, { $setOnInsert: { party: `DEMO Party ${i + 1}`, partyAbbreviation: `DP${i + 1}`, scopeType: 'COUNTY', ballotOrder: i + 1, sourceId: src!._id } }, { upsert: true });
  }
  for (const [i, name] of ['DEMO Ward Candidate One', 'DEMO Ward Candidate Two'].entries()) {
    await Candidate.updateOne({ electionId: election._id, position: 'MCA', scopeRefId: ward!._id, fullName: name }, { $setOnInsert: { party: `DEMO Party ${i + 1}`, partyAbbreviation: `DP${i + 1}`, scopeType: 'WARD', ballotOrder: i + 1, sourceId: src!._id } }, { upsert: true });
  }
  const pw = process.env.DEMO_PASSWORD ?? 'demo-password-change-me';
  const hash = await hashPassword(pw);
  const mk = async (email: string, fullName: string, role: string, extra: Record<string, unknown> = {}) =>
    User.findOneAndUpdate({ email }, { $setOnInsert: { email, fullName, role, passwordHash: hash, mustChangePassword: false, ...extra } }, { upsert: true, new: true });
  await mk('demo-admin@example.org', 'DEMO Administrator', 'SUPER_ADMIN');
  await mk('demo-verifier@example.org', 'DEMO Verifier', 'VERIFICATION_OFFICER');
  await mk('demo-verifier2@example.org', 'DEMO Second Verifier', 'VERIFICATION_OFFICER');
  await mk('demo-finance@example.org', 'DEMO Finance Officer', 'FINANCE_OFFICER');
  const agent = await mk('demo-agent@example.org', 'DEMO Agent', 'AGENT', { agentCode: 'AGT-DEMO0001' });
  await AgentAssignment.updateOne(
    { userId: agent!._id, electionId: election._id, pollingStationId: stations[0]!._id, active: true },
    { $setOnInsert: { countyId: garissa._id, constituencyId: cons!._id, wardId: ward!._id } },
    { upsert: true }
  );
  return { electionId: String(election._id), stationIds: stations.map((s) => String(s!._id)), password: pw };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await connectMongo();
  const r = await seedDemo();
  console.log('DEMO data created (synthetic, for local testing only):', r.electionId);
  console.log('Users: demo-admin@example.org, demo-verifier@example.org, demo-verifier2@example.org, demo-finance@example.org, agent AGT-DEMO0001');
  await disconnectMongo();
}
